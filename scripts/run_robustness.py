"""
Two robustness checks across the validated regions, written to docs/robustness/:

A. Calibration transfer. The calibration fitted in one region is applied unchanged to
   another region and compared with what Aqua MODIS really observed there.
B. MODIS switched off before and after Aqua's orbit drift. The switch-off test is run
   with MODIS removed for 2021-22 (data up to 2022) and for 2023-24 (all data). Aqua's
   overpass time was stable until 2022 and drifted later in 2023-24.

    python scripts/run_robustness.py
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import replace

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)

from engine.pipeline import (AnalysisConfig, calibration_transfer_test, json_safe,  # noqa: E402
                             load_dataset, modis_switch_off_test, run_analysis)

REGIONS = [("California", "data/firms", "case_study"),
           ("Portugal", "data/regions/portugal", "case_study_portugal"),
           ("Northern Australia", "data/regions/australia", "case_study_australia")]
PLATFORMS = [("NOAA20", "NOAA-20"), ("SNPP", "Suomi-NPP")]


def _pct(v):
    return "n/a" if v is None else f"{v:+.1f} %"


def _num(v):
    return "n/a" if v is None else f"{v:.1f} %"


def main() -> int:
    data, full = {}, {}
    for name, folder, _ in REGIONS:
        detections, manifest, _ = load_dataset(os.path.join(ROOT, folder))
        data[name] = (detections, manifest)
        full[name] = run_analysis(detections, manifest, AnalysisConfig())
        print(f"{name}: analysed")

    transfer = []
    for code, label in PLATFORMS:
        for src, *_ in REGIONS:
            for dst, *_ in REGIONS:
                if src != dst:
                    r = calibration_transfer_test(full[src], full[dst], code)
                    transfer.append({"platform": code, "source": src, "target": dst, **r})

    drift = []
    for name, _, _ in REGIONS:
        detections, manifest = data[name]
        late = modis_switch_off_test(detections, manifest, full[name], "2023-01-01")
        early_full = run_analysis(detections, manifest, replace(full[name].config, end="2022-12-31"))
        early = modis_switch_off_test(detections, manifest, early_full, "2021-01-01")
        for tag, r in (("2021-22", early), ("2023-24", late)):
            drift.append({"region": name, "withheld": tag, **{k: v for k, v in r.items() if k != "calendar"}})
        print(f"{name}: switch-off before and after the drift done")

    out_dir = os.path.join(ROOT, "docs", "robustness")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "report.json"), "w", encoding="utf-8") as handle:
        json.dump(json_safe({"transfer": transfer, "switch_off_by_period": drift}), handle, indent=1)

    lines = ["# Robustness checks", "",
             "Generated by `python scripts/run_robustness.py` from the three validated regions "
             "(NASA FIRMS standard-processing data; reference scale Aqua MODIS).", "",
             "## A. Does a calibration transfer between regions?", "",
             "The calibration fitted in the source region (all of its years) is applied unchanged to the "
             "target region and compared with what Aqua MODIS really observed there, month by month. "
             "The target region's own result is its held-out (leave-years-out) score, for comparison. "
             "Months count only if every day has both the platform and Aqua.", ""]
    for code, label in PLATFORMS:
        lines += [f"**{label} VIIRS**", "",
                  "| Calibration from | Applied to | Months | Raw hot spots | Active cells: total | Active cells: median monthly error | Own calibration (held-out): total / monthly error | FRP: total | FRP: median monthly error |",
                  "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for r in transfer:
            if r["platform"] != code:
                continue
            if not r.get("available"):
                lines.append(f"| {r['source']} | {r['target']} | | | {r.get('reason')} | | | | |")
                continue
            c, f, own = r["count"], r["frp"], r["own_region_held_out"]["count"] or {}
            lines.append(f"| {r['source']} | {r['target']} | {r['months']} | {_pct(r['raw_hotspot_bias_pct'])} | "
                         f"{_pct(c.get('total_bias_pct'))} | {_num(c.get('median_abs_pct_error'))} | "
                         f"{_pct(own.get('total_bias_pct'))} / {_num(own.get('median_abs_pct_error'))} | "
                         f"{_pct(f.get('total_bias_pct'))} | {_num(f.get('median_abs_pct_error'))} |")
        lines.append("")
    lines += ["## B. MODIS switched off before and after Aqua's orbit drift", "",
              "Aqua's median daytime detection time was stable until 2022 and moved later in 2023-24 (see the "
              "observing-system check in each region's report). The switch-off test is run twice: MODIS removed "
              "for 2021-22 using data up to 2022 (calibration on April 2018 to December 2020, fewer years), and "
              "MODIS removed for 2023-24 using all data (calibration on April 2018 to December 2022).", "",
              "| Region | MODIS removed | Months | Raw VIIRS | Active cells: total | Active cells: median monthly error | Inside 90 % band | FRP: total | FRP: median monthly error |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in drift:
        if not r.get("available"):
            lines.append(f"| {r['region']} | {r['withheld']} | | | {r.get('reason')} | | | | |")
            continue
        c, f = r["scores"]["count"], r["scores"]["frp"]
        lines.append(f"| {r['region']} | {r['withheld']} | {len(r['months'])} | {_pct(r['raw_viirs_hotspot_bias_pct'])} | "
                     f"{_pct(c.get('total_bias_pct'))} | {_num(c.get('median_abs_pct_error'))} | "
                     f"{_num(r.get('inside_90pct_band_pct'))} | {_pct(f.get('total_bias_pct'))} | "
                     f"{_num(f.get('median_abs_pct_error'))} |")
    lines.append("")
    with open(os.path.join(out_dir, "REPORT.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print("Wrote docs/robustness/REPORT.md and report.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
